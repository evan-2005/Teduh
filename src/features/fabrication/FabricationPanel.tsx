import { useMemo } from 'react';
import { SourceBadge } from '../../components/SourceBadge';
import { dataset, graph } from '../../data/dataset';
import { useInterventions } from '../../hooks/useInterventions';
import { formatMyr } from '../../lib/format';
import { coveredLengthM, shelterBuiltLengthM, type PlannerSettings } from '../../lib/planner';
import { useScenarioStore } from '../../store/scenario';
import type { FabricationSpec, Intervention } from '../../types';
import { shelterElevationSvg } from './elevation';
import { downloadFile, toCsv, toJson } from './export';
import { buildShelterSpec, generateTreeSpec } from './spec';

const DIMENSION_LABELS: Readonly<Record<string, string>> = {
  lengthM: 'Length (m)',
  widthM: 'Width (m)',
  heightM: 'Clear height (m)',
  modules: 'Modules',
  posts: 'Posts',
  footings: 'Footings',
  roofAreaM2: 'Roof area (m²)',
  gutterM: 'Gutter (m)',
  pitLengthM: 'Pit length (m)',
  pitWidthM: 'Pit width (m)',
  pitDepthM: 'Pit depth (m)',
  soilVolumeM3: 'Soil mix (m³)',
  rootBarrierM: 'Root barrier (m)',
  stakes: 'Stakes',
  maintenanceVisits: 'Care visits (2 yrs)',
  trees: 'Trees',
  rowLengthM: 'Row length (m)',
};

/** The build spec under the planner settings: the chosen species, spacing and walkway length. */
function specFor(intervention: Intervention, planner: PlannerSettings): FabricationSpec {
  const { neighbourhood, unitCosts } = dataset;
  const lengthM = coveredLengthM(intervention, graph.lengthBySegment);
  if (intervention.type === 'tree') {
    const species = unitCosts.speciesSuggestions[planner.speciesIndex];
    const chosen = { ...unitCosts, speciesSuggestions: species ? [species] : unitCosts.speciesSuggestions };
    return generateTreeSpec(intervention, chosen, lengthM, planner.treeSpacingM);
  }
  const covered = neighbourhood.segments.filter((s) => intervention.segmentIds.includes(s.id));
  const widthM = Math.max(0, ...covered.map((s) => s.widthM));
  return buildShelterSpec(intervention, shelterBuiltLengthM(lengthM, planner), widthM, unitCosts);
}

const MATCH_TOLERANCE = 0.02;

/** Say whether the simulator's cost agrees with the bill of materials. */
function costNote(planningCost: number, bottomUpCost: number): string {
  const agrees = Math.abs(planningCost - bottomUpCost) <= bottomUpCost * MATCH_TOLERANCE;
  return agrees
    ? `This matches the ${formatMyr(planningCost)} the simulator uses for this item (rounded). Replace it with a contractor quote before any decision.`
    : `The simulator uses a planning figure of ${formatMyr(planningCost)} for this item. The bottom-up total above is built from unit costs and can differ; replace both with a contractor quote before any decision.`;
}

const fileStem = (spec: FabricationSpec): string => `teduh-fabrication-${spec.interventionId}`;

export function FabricationPanel() {
  const selectedId = useScenarioStore((s) => s.selectedInterventionId);
  const selectIntervention = useScenarioStore((s) => s.selectIntervention);
  const planner = useScenarioStore((s) => s.planner);
  const intervention = useInterventions().find((i) => i.id === selectedId) ?? null;
  const spec = useMemo(
    () => (intervention ? specFor(intervention, planner) : null),
    [intervention, planner],
  );

  if (!intervention || !spec) {
    return (
      <section className="card card--stub" aria-label="Fabrication pack">
        <h3 className="card__title">Fabrication pack</h3>
        <p className="card__hint">Select a shelter or tree on the map.</p>
      </section>
    );
  }

  // The SVG string is generated by shelterElevationSvg from numbers and fixed labels only.
  const elevation = spec.type === 'shelter' ? shelterElevationSvg(spec) : null;

  return (
    <section className="card fabrication" aria-label="Fabrication pack">
      <div className="fabrication__head">
        <h3 className="card__title">Fabrication pack: {intervention.name}</h3>
        <button type="button" className="link-button" onClick={() => selectIntervention(null)}>
          Close
        </button>
      </div>

      {elevation && (
        <div className="fabrication__drawing" dangerouslySetInnerHTML={{ __html: elevation }} />
      )}

      <table className="compare">
        <tbody>
          {Object.entries(spec.dimensions).map(([key, value]) => (
            <tr key={key}>
              <th scope="row">{DIMENSION_LABELS[key] ?? key}</th>
              <td className="num">{value}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <h4 className="fabrication__sub">Bill of materials</h4>
      <table className="compare bom">
        <thead>
          <tr>
            <th scope="col">Item</th>
            <th scope="col">Qty</th>
            <th scope="col">Total</th>
          </tr>
        </thead>
        <tbody>
          {spec.bom.map((line) => (
            <tr key={line.item}>
              <th scope="row">{line.item}</th>
              <td className="num">
                {line.qty} {line.unit}
              </td>
              <td className="num">{formatMyr(line.total)}</td>
            </tr>
          ))}
        </tbody>
        <tfoot>
          <tr>
            <th scope="row">Bottom-up total</th>
            <td />
            <td className="num">{formatMyr(spec.totalCost)}</td>
          </tr>
        </tfoot>
      </table>
      <p className="card__hint">
        Cost data: <SourceBadge source={dataset.unitCosts.costSource} />
      </p>
      <p className="card__hint">{costNote(intervention.installCost, spec.totalCost)}</p>

      <ul className="fabrication__assumptions">
        {spec.assumptions.map((a) => (
          <li key={a}>{a}</li>
        ))}
      </ul>

      <div className="fabrication__actions">
        <button
          type="button"
          className="button"
          onClick={() => downloadFile(`${fileStem(spec)}.csv`, toCsv(spec), 'text/csv')}
        >
          Download CSV
        </button>
        <button
          type="button"
          className="button"
          onClick={() => downloadFile(`${fileStem(spec)}.json`, toJson(spec), 'application/json')}
        >
          Download JSON
        </button>
      </div>
      <p className="fabrication__disclaimer">{spec.disclaimer}</p>
    </section>
  );
}
